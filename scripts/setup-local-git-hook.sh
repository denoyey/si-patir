#!/bin/bash
# ==============================================================================
# SI-PATIR: Setup Local Git Hook
# Menghubungkan repo lokal ke SI-PATIR Backend tanpa memerlukan tunnel
# ==============================================================================

TARGET_REPO="$1"

if [ -z "$TARGET_REPO" ]; then
  echo "Penggunaan: ./setup-local-git-hook.sh /path/ke/repo/kamu"
  echo "Contoh: ./setup-local-git-hook.sh ~/my-project"
  exit 1
fi

HOOK_FILE="$TARGET_REPO/.git/hooks/post-commit"

if [ ! -d "$TARGET_REPO/.git" ]; then
  echo "Error: Direktori '$TARGET_REPO' bukan repositori Git (.git tidak ditemukan)."
  exit 1
fi

cat << 'EOF' > "$HOOK_FILE"
#!/bin/sh
# Auto-generated by SI-PATIR
LAST_COMMIT_MSG=$(git log -1 --pretty=%B | tr -d '\n')
AUTHOR_NAME=$(git log -1 --pretty=%an)
COMMIT_HASH=$(git log -1 --pretty=%h)

# Kirim sinyal commit ke backend SI-PATIR di localhost:5000
curl -s -X POST http://localhost:5000/api/webhooks/github \
  -H "Content-Type: application/json" \
  -d "{\"commits\": [{\"message\": \"$LAST_COMMIT_MSG\", \"author\": {\"name\": \"$AUTHOR_NAME\"}, \"url\": \"commit/$COMMIT_HASH\"}]}" > /dev/null 2>&1 &
EOF

chmod +x "$HOOK_FILE"
echo "✅ Berhasil memasang local git hook di: $HOOK_FILE"
echo "Sekarang setiap kali kamu 'git commit', SI-PATIR akan otomatis memproses tugas & mengirim notifikasi!"

